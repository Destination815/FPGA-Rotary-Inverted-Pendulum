P=Path(__file__).resolve().parent
OPS=['CONST','LOAD','STORE','ADD','SUB','NEG','ABS','SIGN','MIN','MAX','CLIP','SEL','AND','OR','NOT','LT','LE','GT','GE','EQ','NE','BAND','SHR','SHL','MUL','SIN','COS','TANH','END']
OP={n:i for i,n in enumerate(OPS)}
def generate():
 names=sorted({x[1]for x in PROGRAM}|{'theta','phi','omega','velocity','kick_sign','mode'});reg={n:i for i,n in enumerate(names)};assert len(reg)<128
 code=[];depth=0;maximum=0
 def emit(op,arg=0,delta=0):
  nonlocal depth,maximum
  code.append((OP[op],arg));depth+=delta;maximum=max(maximum,depth);assert depth>=0
 def expr(n):
  if isinstance(n,ast.Constant):emit('CONST',n.value,1)
  elif isinstance(n,ast.Name):emit('LOAD',reg[n.id],1)
  elif isinstance(n,ast.BinOp):
   expr(n.left);expr(n.right);emit({ast.Add:'ADD',ast.Sub:'SUB',ast.Mult:'MUL',ast.BitAnd:'BAND',ast.RShift:'SHR',ast.LShift:'SHL'}[type(n.op)],delta=-1)
  elif isinstance(n,ast.UnaryOp):
   expr(n.operand)
   if not isinstance(n.op,ast.UAdd):emit({ast.USub:'NEG',ast.Not:'NOT'}[type(n.op)])
  elif isinstance(n,ast.BoolOp):
   expr(n.values[0])
   for v in n.values[1:]:expr(v);emit('AND'if isinstance(n.op,ast.And)else'OR',delta=-1)
  elif isinstance(n,ast.Compare):
   expr(n.left);expr(n.comparators[0]);emit({ast.Lt:'LT',ast.LtE:'LE',ast.Gt:'GT',ast.GtE:'GE',ast.Eq:'EQ',ast.NotEq:'NE'}[type(n.ops[0])],delta=-1)
  elif isinstance(n,ast.IfExp):expr(n.test);expr(n.body);expr(n.orelse);emit('SEL',delta=-2)
  elif isinstance(n,ast.Call):
   for a in n.args:expr(a)
   emit({'abs':'ABS','sign':'SIGN','min':'MIN','max':'MAX','clip':'CLIP','sinlut':'SIN','coslut':'COS','tanhlut':'TANH'}[n.func.id],delta=1-len(n.args))
  else:raise ValueError(ast.dump(n))
 for op in PROGRAM:
  expr(ast.parse(op[2],mode='eval').body)
  if op[0]=='mul':expr(ast.parse(op[3],mode='eval').body);emit('MUL',op[4],-1)
