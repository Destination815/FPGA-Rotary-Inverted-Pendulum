"""Compact microcoded implementation of the unchanged IntegerSwing program.
Single synchronous register file and instruction ROM; bounded stack; serial multiply.
No controller coefficients or arithmetic rounding rules are changed.
"""
from pathlib import Path
import ast,json,re
