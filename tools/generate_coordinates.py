"""Generate FPGA constants from the single reviewed coordinate contract; no serial."""
from pathlib import Path
import json,sys,math
ROOT=Path(__file__).resolve().parents[1]
def generated():
 p=json.loads((ROOT/'calibration/encoder_calibration.json').read_text(encoding='utf-8'))
 assert p['counts_per_output_turn']==p['cpr_num']/p['cpr_den']
 assert p['physical_rpc_q24']==round(2*math.pi/(p['cpr_num']/p['cpr_den'])*2**24) and p['legacy_q16_per_count']==396
 assert 0<p['physical_rpc_q24']<(1<<17) and 0<p['target_legacy_per_physical_q24']<(1<<25)
 assert p['target_legacy_per_physical_q24']==round((396*256)/97763*2**24)
 values={'BUILD':"32'h"+p['build'].lower(),'TOKEN':"32'h%08x"%p['contract_token'],'SCHEMA':"16'h%04x"%p['wire_schema'],'CPR_NUM':"32'd"+str(p['cpr_num']),'CPR_DEN':"32'd"+str(p['cpr_den']),'CPR_ROUNDED':"16'd"+str(round(p['cpr_num']/p['cpr_den'])),'PHYSICAL_RPC_Q24':"32'd"+str(p['physical_rpc_q24']),'LEGACY_Q16_PER_COUNT':"32'sd396",'TARGET_K_Q24':"32'd"+str(p['target_legacy_per_physical_q24'])}
 return '// Generated by tools/generate_coordinates.py. Internal legacy units are NOT physical radians.\n`ifndef J280_COORDINATES_VH\n`define J280_COORDINATES_VH\n'+''.join('`define J280_C_'+k+' '+v+'\n' for k,v in values.items())+'`endif\n'
if __name__=='__main__':
 target=ROOT/'fpga/src/j280_coordinates.vh';text=generated()
 if '--check' in sys.argv:
  assert target.read_text()==text,'Regenerate coordinate constants';print('PASS coordinate constants')
 else:target.write_text(text)
